// 저장된 선택 > 브라우저 언어 > 영어
function pickLang() {
  try {
    const saved = localStorage.getItem('lang');
    if (saved && I18N[saved]) return saved;
  } catch (e) { /* 사생활 보호 모드 등 */ }
  // "fr-FR" "ja-JP" 처럼 지역이 붙어 온다. 앞 두 글자만 본다.
  const n = (navigator.language || '').toLowerCase().slice(0, 2);
  return I18N[n] ? n : 'en';
}
